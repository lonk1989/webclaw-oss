  function bilibiliEmbedUrl(bvid) {
    const id = String(bvid || "").trim();
    if (!id) return "";
    const bv = id.startsWith("BV") || id.startsWith("bv") ? id : `BV${id}`;
    return `https://player.bilibili.com/player.html?bvid=${encodeURIComponent(
      bv
    )}&page=1&high_quality=1&danmaku=0`;
  }

  function getCommandHelp(cmd) {
    const kw = String(cmd?.keyword || "").trim();
    const hit = HELP[kw];
    if (hit) {
      return {
        bvid: hit.bvid || "",
        embedUrl: bilibiliEmbedUrl(hit.bvid),
        md: hit.md,
      };
    }
    const name = String(cmd?.name || kw || "指令").trim();
    const desc = String(cmd?.description || "").trim();
    const kind = cmd?.kind === "macro" ? "宏" : "指令";
    let md = `## ${name}\n\n`;
    md += desc ? `${desc}\n\n` : `自定义${kind}。\n\n`;
    md += `### 用法\n\n\`\`\`text\n${kw || name} …\n\`\`\`\n`;
    if (cmd?.kind === "macro" && cmd?.macro_body) {
      md += `\n宏体会展开为多步文本后再执行。\n`;
    }
    return { bvid: "", embedUrl: "", md };
  }

  global.CmdHelp = {
    HELP,
    getCommandHelp,
    bilibiliEmbedUrl,
  };
