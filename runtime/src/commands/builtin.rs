/// 已从内置列表移除的指令 id（加载 commands.json 时会自动删除）
pub const RETIRED_BUILTIN_IDS: &[&str] = &["builtin_close_dialog", "builtin_merge_attendance"];

pub fn is_retired_builtin(cmd: &CommandDef) -> bool {
    if RETIRED_BUILTIN_IDS.contains(&cmd.id.as_str()) {
        return true;
    }
    // 合并考勤已迁至「脚本」库，旧关键词指令一律退役
    if cmd.keyword == "合并考勤数据" && (cmd.builtin || cmd.runner == RunnerKind::Rhai) {
        return true;
    }
    cmd.builtin && cmd.kind == CommandKind::Macro && cmd.name == "关闭弹窗"
}

